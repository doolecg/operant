const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('operant', {
  config: () => ipcRenderer.invoke('config'),
  setConfig: patch => ipcRenderer.invoke('config:set', patch),
  defaults: () => ipcRenderer.invoke('config:defaults'),
  createPty: opts => ipcRenderer.invoke('pty:create', opts),
  writePty: (id, data) => ipcRenderer.send('pty:write', { id, data }),
  resizePty: (id, cols, rows) => ipcRenderer.send('pty:resize', { id, cols, rows }),
  killPty: id => ipcRenderer.send('pty:kill', { id }),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  openConfig: () => ipcRenderer.send('open-config'),
  configPath: () => ipcRenderer.invoke('config:path'),
  minimize: () => ipcRenderer.send('win:minimize'),
  maximize: () => ipcRenderer.send('win:maximize'),
  close: () => ipcRenderer.send('win:close'),
  newWindow: () => ipcRenderer.send('win:new'),
  windowFocused: () => ipcRenderer.invoke('win:focused'),
  notify: n => ipcRenderer.send('notify', n),
  devtools: () => ipcRenderer.send('devtools'),
  version: () => ipcRenderer.invoke('app:version'),
  startupFolder: () => ipcRenderer.invoke('startup-folder'),
  takeSession: () => ipcRenderer.invoke('session:take'),
  saveSession: snap => ipcRenderer.send('session:save', snap),
  saveAndQuit: () => ipcRenderer.send('app:save-quit'),
  checkUpdate: () => ipcRenderer.send('update:check'),
  installUpdate: () => ipcRenderer.send('update:install'),
  updateState: () => ipcRenderer.invoke('update:state'),
  openReleases: () => ipcRenderer.send('open-releases'),
  openLogFolder: () => ipcRenderer.send('open-log-folder'),
  openLink: (url, second) => ipcRenderer.send('open-link', { url, second }),
  browsers: () => ipcRenderer.invoke('browsers:list'),
  listDir: (dir, hidden) => ipcRenderer.invoke('fs:list', { dir, hidden }),
  isDir: p => ipcRenderer.invoke('fs:is-dir', p),
  readFile: p => ipcRenderer.invoke('fs:read', p),
  watchFile: (key, file) => ipcRenderer.send('fs:watch', { key, file }),
  listFiles: root => ipcRenderer.invoke('fs:files', root),
  gitStatus: dir => ipcRenderer.invoke('git:status', dir),
  gitDiff: opts => ipcRenderer.invoke('git:diff', opts),
  git: (op, arg) => ipcRenderer.invoke('git:' + op, arg), // commit | push | pull | rollback | branches | checkout | last-message
  ask: opts => ipcRenderer.invoke('ask', opts),
  editorName: () => ipcRenderer.invoke('editor:name'),
  openPath: p => ipcRenderer.send('fs:open', p),
  reveal: p => ipcRenderer.send('fs:reveal', p),
  openInIde: p => ipcRenderer.invoke('ide:open', p),
  codegraphVersion: () => ipcRenderer.invoke('codegraph:version'),
  codegraphStartup: () => ipcRenderer.invoke('codegraph:startup'),
  mediaState: () => ipcRenderer.invoke('media:state'),
  media: cmd => ipcRenderer.send('media:command', cmd),
  usageSummary: () => ipcRenderer.invoke('usage:summary'),
  usageSeries: range => ipcRenderer.invoke('usage:series', range),
  usageLimits: () => ipcRenderer.invoke('usage:limits'),
  usageBreakdown: opts => ipcRenderer.invoke('usage:breakdown', opts),
  clipboardHasImage: () => ipcRenderer.invoke('clipboard:has-image'),
  pathForFile: f => webUtils.getPathForFile(f),
  on: (ch, fn) => ipcRenderer.on(ch, (_e, d) => fn(d)),
  onControl: fn => ipcRenderer.on('control', (_e, d) => fn(d)),
  controlReply: r => ipcRenderer.send('control:reply', r),
  abortOpenCode: ptyId => ipcRenderer.invoke('opencode:abort', { ptyId }),
  summarizeOpenCode: ptyId => ipcRenderer.invoke('opencode:summarize', { ptyId }),
});
